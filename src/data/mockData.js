// Storage helper functions with automatic cache migration for official VMS data
const OFFICIAL_VMS_SCHEMA_VERSION = "2026_VMS_OFFICIAL_CATALOG_V5";

export function getStoredData(key, fallback) {
  try {
    const currentVersion = localStorage.getItem('izri_schema_version');
    if (currentVersion !== OFFICIAL_VMS_SCHEMA_VERSION) {
      // Automatically refresh to official VMS models, prices, and photos
      localStorage.setItem('izri_schema_version', OFFICIAL_VMS_SCHEMA_VERSION);
      localStorage.removeItem(`izri_${key}`);
      return fallback;
    }
    const item = localStorage.getItem(`izri_${key}`);
    if (!item) return fallback;
    const parsed = JSON.parse(item);
    
    // Safety check for outdated model identifiers
    if (key === 'motorcycles' && Array.isArray(parsed)) {
      const hasOldModels = parsed.some(m => 
        m.id === 'vms-cux-125' || 
        m.id === 'vms-s-125' || 
        m.id === 'vms-x-250' || 
        m.name === 'VMS CUX 125' ||
        m.image === '/models/cux125.webp'
      );
      if (hasOldModels) {
        localStorage.setItem(`izri_${key}`, JSON.stringify(fallback));
        return fallback;
      }
    }
    return parsed;
  } catch (e) {
    console.warn(`Error reading localStorage for ${key}`, e);
    return fallback;
  }
}

export function saveStoredData(key, value) {
  try {
    localStorage.setItem('izri_schema_version', OFFICIAL_VMS_SCHEMA_VERSION);
    localStorage.setItem(`izri_${key}`, JSON.stringify(value));
  } catch (e) {
    console.warn(`Error writing localStorage for ${key}`, e);
  }
}
